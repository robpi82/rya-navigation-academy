const SHORT: Record<string, string> = {
  port: 'Backbordtonne (Fahrwasserrand links beim Einlaufen)',
  starboard: 'Steuerbordtonne (Fahrwasserrand rechts beim Einlaufen)',
  'pref-stbd': 'Abzweigung, bevorzugtes Fahrwasser an Steuerbord',
  'pref-port': 'Abzweigung, bevorzugtes Fahrwasser an Backbord',
  north: 'Nordtonne',
  east: 'Osttonne',
  south: 'Südtonne',
  west: 'Westtonne',
  isolated: 'Einzelgefahrenzeichen',
  safe: 'Mitte-Fahrwasser-/Ansteuerungstonne',
  special: 'Spezialtonne',
  'new-danger': 'Notkennzeichnung neuer Gefahren',
}

const IDENTIFY: Question[] = BUOYS.map((b, i): MultipleChoiceQuestion => {
  const others = BUOYS.filter((o) => o.id !== b.id)
  // Ablenker: bewusst ähnliche Zeichen zuerst (gleiche Gruppe), dann reihum
  const distractors = [...others.filter((o) => o.group === b.group), ...others.filter((o) => o.group !== b.group)].slice(0, 3)
  const options = distractors.map((d) => SHORT[d.id])
  const correctIndex = i % 4
  options.splice(correctIndex, 0, SHORT[b.id])
  return {
    id: `dt-b-${b.id}`,
    type: 'mc',
    topic: 'buoyage',
    difficulty: b.group === 'other' ? 2 : 1,
    level: 'day-skipper',
    category: 'diagram',
    prompt: 'Welches Seezeichen (IALA-System A) ist abgebildet?',
    buoy: b.id,
    options,
    correctIndex,
    solution: SHORT[b.id],
    steps: [`Aussehen: ${b.look}; Toppzeichen: ${b.topmark}.`, b.meaning, `Passieren: ${b.action}`],
  }
})

